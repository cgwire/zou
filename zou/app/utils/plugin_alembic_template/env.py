"""
Shared Alembic env.py for all Zou plugins.

Zou owns this file (it is in
``zou/app/utils/plugin_alembic_template/``) and points alembic at it
through ``script_location``. Plugins ship only a ``migrations/versions/``
directory with their revision files. They do not ship env.py,
script.py.mako or alembic.ini.

``_build_plugin_alembic_config`` in ``zou/app/utils/plugins.py`` gives
the plugin path in ``alembic_cfg.attributes['plugin_path']``.
"""

import importlib.util
import logging
import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import create_engine, pool

from zou.app import db
from zou.app.utils.plugins import PluginManifest

config = context.config

# zou.app.utils.plugins._build_plugin_alembic_config injects the plugin
# path. If env.py runs outside that flow (e.g. by hand), make a best-effort
# guess from the parent directory of script_location, so that the old
# layout (env.py inside the plugin) continues to work.
plugin_path = Path(
    config.attributes.get("plugin_path")
    or Path(config.get_main_option("script_location")).resolve().parent
)
manifest = PluginManifest.from_plugin_path(plugin_path)

plugin_prefix = f"plugin_{manifest['id']}_"
module_name = f"_plugin_models_{manifest['id']}"

# Do not run models.py again if db.metadata already has the plugin tables.
# The pre_install hook calls _import_plugin_module, which indirectly imports
# models.py. Without this guard, alembic would try to define the same Table
# object again and crash with
# "Table 'plugin_<id>_…' is already defined for this MetaData instance".
already_loaded = any(
    table.startswith(plugin_prefix) for table in db.metadata.tables
)
if not already_loaded:
    models_path = plugin_path / "models.py"
    if models_path.exists():
        spec = importlib.util.spec_from_file_location(module_name, models_path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[module_name] = module
        spec.loader.exec_module(module)


if config.config_file_name:
    # disable_existing_loggers is True by default and would silence all
    # loggers created before the migration starts. This includes the
    # app.logger of Flask, because plugin installs run in the same process.
    fileConfig(config.config_file_name, disable_existing_loggers=False)
logger = logging.getLogger("alembic.env")


def include_object(object, name, type_, reflected, compare_to):
    """
    Restrict alembic to the tables of this plugin.
    """
    if type_ == "table":
        return name.startswith(plugin_prefix)
    return True


def render_item(type_, obj, autogen_context):
    """
    Render UUIDType columns with the correct import in autogenerated
    files.
    """
    import sqlalchemy_utils

    if type_ == "type" and isinstance(
        obj, sqlalchemy_utils.types.uuid.UUIDType
    ):
        autogen_context.imports.add("import sqlalchemy_utils")
        autogen_context.imports.add("import uuid")
        return (
            "sqlalchemy_utils.types.uuid.UUIDType(binary=False),"
            " default=uuid.uuid4"
        )
    return False


def run_migrations_online():
    """
    Run the plugin migrations on the database. Record them in the
    alembic_version_<id> table of the plugin.
    """
    url = config.get_main_option("sqlalchemy.url")
    connectable = create_engine(url, poolclass=pool.NullPool)
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=db.metadata,
            version_table=f"alembic_version_{manifest['id']}",
            compare_type=True,
            include_object=include_object,
            render_item=render_item,
        )
        with context.begin_transaction():
            context.run_migrations()


run_migrations_online()
